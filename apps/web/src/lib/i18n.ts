const MESSAGES: Record<Locale, Record<MessageKey, string>> = { en, es };

export function t(locale: Locale, key: MessageKey): string {
  return MESSAGES[locale][key] ?? en[key];
}

/** `t` plus `{name}` placeholders, so word order stays the translator's call ("{n} of {total}" vs "{n} de {total}"). */
export function tf(locale: Locale, key: MessageKey, vars: Record<string, string | number>): string {
  return t(locale, key).replace(/\{(\w+)\}/g, (m, name: string) => (name in vars ? String(vars[name]) : m));
}

/** A run/task/approval status word in the chosen language; an unknown status falls back to the raw value with spaces. */
export function statusLabel(locale: Locale, status: string): string {
  const key = `status.${status}`;
  return key in en ? t(locale, key as MessageKey) : status.replace(/_/g, " ");
}

/** "{span} ago" / "hace {span}" style relative time from a compact span such as "3h". */
export function relativeSpan(locale: Locale, span: string, future: boolean): string {
  return tf(locale, future ? "time.in" : "time.ago", { span });
}
